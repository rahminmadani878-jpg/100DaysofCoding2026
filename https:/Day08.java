public class Main {
	public static void main(String[] args) {
        // DEKLARASI —> siapkan variabel, belum ada nilai
        int level;

        //  INISIALISASI —> beri nilai PERTAMA
        level = 1;
        System.out.println("Sebelum diubah : " + level);

        //  UPDATE —> ganti nilai dengan yang BARU
        level = 100;
        System.out.println("Sesudah diubah : " + level);
	}
}
