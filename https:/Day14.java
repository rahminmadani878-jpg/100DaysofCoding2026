public class Main {
	public static void main(String[] args) {
        
        // PENJUMLAHAN (+)
        int angka1 = 20;
        int angka2 = 10;
        int hasilTambah = angka1 + angka2;
        
        //  PENGURANGAN (-)
        int angka3 = 40;
        int angka4 = 30;
        int hasilKurang = angka3 - angka4;
        
        // MENAMPILKAN HASIL
        System.out.println("Penjumlahan: " + angka1 + " + " + angka2 + " = " + hasilTambah);
        System.out.println("Pengurangan: " + angka3 + " - " + angka4 + " = " + hasilKurang);
	}
}
