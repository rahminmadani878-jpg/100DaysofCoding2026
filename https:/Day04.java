public class Main {
	public static void main(String[] args) {
        // byte — untuk angka kecil
        byte nilaiAtas = 6;
        System.out.println("Kartu: " + nilaiAtas );

        // short — untuk angka lebih besar dari byte
        short poinSaya = 120;
        System.out.println("Poin — Saya: " + poinSaya);

        // int — angka bulat biasa tanpa tanda koma
        int totalPoin = 2500;
        System.out.println("Total Poin: " + totalPoin);

        // long — untuk bilangan paling besar dan di akhir ada huruf L
        long totalPermainan = 1250000L; 
        System.out.println("Total Permainan: " + totalPermainan);
	}
}
